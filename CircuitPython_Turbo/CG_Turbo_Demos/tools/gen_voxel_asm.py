"""Write turbo_source/voxel_asm.py: the whole VoxelSpace frame as one asm_thumb function.

    python3 tools/gen_voxel_asm.py

The inline assembler only takes immediate shifts, so the per-sample loop is
written out from the template below once per mip level, with and without the
fog blend: rows nearer than the fog have fog 0, which blends to exactly the
palette color, and most pixels are drawn there. Slot offsets come from
turbo_source/voxel.py's F_* constants; frame_asm() must produce exactly the pixels of
voxel.render().
"""

from spdx import HEADER
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEVELS = 3

slots = {}
for name, value in re.findall(r"^(F_\w+) = const\((\d+)\)", (ROOT / "turbo_source" / "voxel.py").read_text(), re.M):
    slots[name] = int(value) * 4
    if slots[name] > 124:
        raise SystemExit("%s is past the 124-byte ldr/str offset limit" % name)


def at(name):
    return "[r7, %d]" % slots[name]


HEAD = '''"""Generated by tools/gen_voxel_asm.py from turbo_source/voxel.py's F_* slots: edit those.

frame_asm(args_address) renders a whole VoxelSpace frame, the same pixels as
voxel.render(). Relabelled as viper by tools/asm_to_viper.py, so the argument
object is at [r3]. Specialised for a 512-texel map and a 320-wide back buffer.
"""

import micropython


@micropython.asm_thumb
def frame_asm(r0, r1, r2, r3):
    # r7: args. Row loop: r0 px, r1 py, r2 column buffer pointer,
    # r8 dx, r9 dy, r10 terrain level, r11 hinvz, r12 C (see voxel.F_HORIZON).
    ldr(r7, [r3, 0])
    push({r7})
    asr(r7, r7, 1)
    mov(r3, r8)  # r8-r11 belong to the caller
    mov(r4, r9)
    mov(r5, r10)
    mov(r6, r11)
    push({r3, r4, r5, r6})

    # every column starts empty
    ldr(r2, %(F_YBUF)s)
    ldr(r3, %(F_YEND)s)
    ldr(r4, %(F_HEIGHT)s)
    label(clear)
    str(r4, [r2, 0])
    add(r2, r2, 4)
    cmp(r2, r3)
    blt(clear)

    ldr(r6, %(F_ROWS)s)
    str(r6, %(F_ROW_NEXT)s)
    label(row)
    ldr(r6, %(F_ROW_NEXT)s)
    ldr(r0, [r6, 0])  # z
    ldr(r2, %(F_LEFT_X)s)
    mul(r2, r0)
    ldr(r3, %(F_CAM_X)s)
    add(r2, r2, r3)
    lsl(r2, r2, 7)
    str(r2, %(F_PX)s)
    ldr(r2, %(F_LEFT_Y)s)
    mul(r2, r0)
    ldr(r3, %(F_CAM_Y)s)
    add(r2, r2, r3)
    lsl(r2, r2, 7)
    str(r2, %(F_PY)s)
    ldr(r2, %(F_STEP_X)s)
    mul(r2, r0)
    lsl(r2, r2, 7)
    mov(r8, r2)
    ldr(r2, %(F_STEP_Y)s)
    mul(r2, r0)
    lsl(r2, r2, 7)
    mov(r9, r2)
    ldr(r0, [r6, 4])  # invz
    ldr(r2, %(F_CAM_H)s)
    mul(r2, r0)
    ldr(r3, %(F_CAM_H_FRAC)s)
    mul(r3, r0)
    lsr(r3, r3, 8)
    add(r2, r2, r3)
    ldr(r3, %(F_HORIZON)s)
    add(r2, r2, r3)
    # terrain heights scaled around the base: hinvz = invz >> shift, and
    # C -= base * (invz - hinvz)
    ldr(r3, %(F_HEIGHT_SHIFT)s)
    mov(r4, r0)
    lsr(r4, r3)
    mov(r11, r4)
    sub(r3, r0, r4)
    ldr(r5, %(F_BASE)s)
    mul(r3, r5)
    sub(r2, r2, r3)
    mov(r12, r2)
    ldr(r0, [r6, 8])  # fog
    mov(r2, 32)
    sub(r2, r2, r0)
    str(r2, %(F_FOG_KEEP)s)
    ldr(r2, %(F_FOG_COLOR)s)
    mul(r2, r0)
    str(r2, %(F_FOG_ADD)s)
    ldr(r3, [r6, 12])  # mip level
    add(r6, 16)
    str(r6, %(F_ROW_NEXT)s)
    mov(r5, r0)
    ldr(r0, %(F_PX)s)
    ldr(r1, %(F_PY)s)
    ldr(r2, %(F_YBUF)s)
    # pick the loop for this level and fog (conditional branches only reach
    # 256 bytes, so they go through nearby unconditional ones)
    cmp(r5, 0)
    bne(fogged)
    cmp(r3, 1)
    blt(to0)
    beq(to1)
    b(enter2)
    label(to0)
    b(enter0)
    label(to1)
    b(enter1)
    label(fogged)
    cmp(r3, 1)
    blt(to0f)
    beq(to1f)
    b(enter2f)
    label(to0f)
    b(enter0f)
    label(to1f)
    b(enter1f)
'''

BLEND = '''    # blended toward the fog color
    ldr(r6, %(F_FOG_KEEP)s)
    mul(r3, r6)
    ldr(r6, %(F_FOG_ADD)s)
    add(r3, r3, r6)
    lsr(r3, r3, 5)
    ldr(r6, %(F_SPREAD)s)
    and_(r3, r6)
'''

LEVEL = '''
    label(enter%(L)s)
    ldr(r3, %(F_LEVEL)s)
    mov(r10, r3)
    label(sample%(L)s)
    # texel: level + (py >> %(shift)d) * %(row_bytes)d + (px >> %(shift)d) * 2
    lsr(r3, r0, %(shift)d)
    lsl(r3, r3, 1)
    lsr(r4, r1, %(shift)d)
    lsl(r4, r4, %(row_shift)d)
    add(r3, r3, r4)
    mov(r4, r10)
    add(r3, r3, r4)
    ldrh(r3, [r3, 0])  # height << 8 | palette index
    # top = (C - height * hinvz) >> 12
    lsr(r4, r3, 8)
    mov(r5, r11)
    mul(r4, r5)
    mov(r5, r12)
    sub(r4, r5, r4)
    asr(r4, r4, 12)
    ldr(r5, [r2, 0])  # bottom: the column's highest pixel so far
    cmp(r4, r5)
    bge(next%(L)s)
    cmp(r4, 0)
    bge(on_screen%(L)s)
    mov(r4, 0)
    label(on_screen%(L)s)
    str(r4, [r2, 0])
    # palette color, already spread to 0x07E0F81F form
    lsl(r3, r3, 24)
    lsr(r3, r3, 22)
    ldr(r6, %(F_PAL)s)
    add(r3, r3, r6)
    ldr(r3, [r3, 0])
%(blend)s    lsr(r6, r3, 16)
    orr(r3, r6)  # rgb565 in the low half
    # first pixel: back + column * 2 + top * 640
    ldr(r6, %(F_YBUF)s)
    sub(r6, r2, r6)
    lsr(r6, r6, 1)
    sub(r5, r5, r4)  # pixels to fill
    lsl(r4, r4, 7)
    add(r6, r6, r4)
    lsl(r4, r4, 2)
    add(r6, r6, r4)
    ldr(r4, %(F_BACK)s)
    add(r6, r6, r4)
    movw(r4, 640)
    label(fill%(L)s)
    strh(r3, [r6, 0])
    add(r6, r6, r4)
    sub(r5, r5, 1)
    bgt(fill%(L)s)
    label(next%(L)s)
    mov(r3, r8)
    add(r0, r0, r3)
    mov(r3, r9)
    add(r1, r1, r3)
    add(r2, r2, 4)
    ldr(r3, %(F_YEND)s)
    cmp(r2, r3)
    blt(sample%(L)s)
    b(row_done)
'''

TAIL = '''
    label(row_done)
    ldr(r6, %(F_ROW_NEXT)s)
    ldr(r3, %(F_ROWS_END)s)
    cmp(r6, r3)
    bge(sky)
    b(row)

    # sky in whatever each column has left
    label(sky)
    ldr(r2, %(F_YBUF)s)
    ldr(r1, %(F_BACK)s)
    movw(r6, 640)
    label(sky_column)
    ldr(r3, [r2, 0])
    cmp(r3, 0)
    ble(sky_next)
    ldr(r4, %(F_SKY)s)
    mov(r5, r1)
    label(sky_fill)
    ldr(r0, [r4, 0])
    strh(r0, [r5, 0])
    add(r4, 4)
    add(r5, r5, r6)
    sub(r3, r3, 1)
    bgt(sky_fill)
    label(sky_next)
    add(r1, r1, 2)
    add(r2, r2, 4)
    ldr(r3, %(F_YEND)s)
    cmp(r2, r3)
    blt(sky_column)

    pop({r3, r4, r5, r6})
    mov(r8, r3)
    mov(r9, r4)
    mov(r10, r5)
    mov(r11, r6)
    pop({r0})
'''


def main():
    fields = {name: at(name) for name in slots}
    parts = [HEAD % fields]
    for fogged in (False, True):
        for level in range(LEVELS):
            values = dict(fields)
            values.update(
                L="%d%s" % (level, "f" if fogged else ""),
                shift=23 + level,
                row_bytes=1024 >> level,
                row_shift=10 - level,
                F_LEVEL=at("F_LEVEL%d" % level),
                blend=BLEND % fields if fogged else "",
            )
            parts.append(LEVEL % values)
    parts.append(TAIL % fields)
    out = ROOT / "turbo_source" / "voxel_asm.py"
    out.write_text(HEADER + "".join(parts))
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
