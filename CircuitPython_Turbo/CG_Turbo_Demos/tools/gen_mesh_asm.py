"""Write turbo_source/mesh_asm.py: the 3D model transform as one asm_thumb function.

    python3 tools/gen_mesh_asm.py

transform_asm(block_address) rotates and projects every vertex and vertex
normal (and, for flat shading, every face normal) with the FPU: the same
float32 operations in the same order as tools/mesh_ref.py's transform(), so
the integers are bit-identical. Slot offsets come from turbo_source/mesh.py's X_*
constants.
"""

from spdx import HEADER
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
consts = {
    name: int(value)
    for name, value in re.findall(r"^(\w+) = const\((\d+)\)", (ROOT / "turbo_source" / "mesh.py").read_text(), re.M)
}


HEAD = """\"\"\"Generated by tools/gen_mesh_asm.py: edit that.

transform_asm(block_address): rotate and project a model's vertices, vertex
normals and (if X_FACES_ON) face normals, bit-identical to tools/mesh_ref.py.
Relabelled as viper by tools/asm_to_viper.py, so the argument object is at [r3].
\"\"\"

import micropython


@micropython.asm_thumb
def transform_asm(r0, r1, r2, r3):
"""


def at(name, plus=0):
    offset = 4 * (consts[name] + plus)
    return "[r7, %d]" % offset


def main():
    lines = []
    a = lines.append
    a("ldr(r7, [r3, 0])")
    a("push({r7})")
    a("asr(r7, r7, 1)")
    for i in range(16):
        a("vstr(s%d, %s)" % (16 + i, at("X_SAVE", i)))
    # s16-s24 the rotation, s25 distance, s26 focal, s27-s28 center, s29 depth
    # scale, s30 normal scale, s31 one
    for i in range(9):
        a("vldr(s%d, %s)" % (16 + i, at("X_M", i)))
    for reg, name in (
        ("s25", "X_DISTANCE"),
        ("s26", "X_FOCAL16"),
        ("s27", "X_CENTER_X16"),
        ("s28", "X_CENTER_Y16"),
        ("s29", "X_DEPTH_SCALE"),
        ("s30", "X_NORMAL_SCALE"),
        ("s31", "X_ONE"),
    ):
        a("vldr(%s, %s)" % (reg, at(name)))

    def rotate_row(dst, row, src, tmp="s6"):
        m = 16 + 3 * row
        a("vmul(%s, s%d, %s)" % (dst, m, src[0]))
        a("vmul(%s, s%d, %s)" % (tmp, m + 1, src[1]))
        a("vadd(%s, %s, %s)" % (dst, dst, tmp))
        a("vmul(%s, s%d, %s)" % (tmp, m + 2, src[2]))
        a("vadd(%s, %s, %s)" % (dst, dst, tmp))

    def store(reg, offset, plus_offset=False):
        a("vcvt_s32_f32(%s, %s)" % (reg, reg))
        a("vmov(r4, %s)" % reg)
        if plus_offset:
            a("add(r4, %d)" % consts["NORMAL_OFFSET"])
        a("strh(r4, [r2, %d])" % offset)

    a("ldr(r0, %s)" % at("X_POSITIONS"))
    a("ldr(r1, %s)" % at("X_NORMALS"))
    a("ldr(r2, %s)" % at("X_GEO"))
    a("ldr(r3, %s)" % at("X_VERTS"))
    a("label(vertex)")
    for k in range(3):
        a("vldr(s%d, [r0, %d])" % (k, 4 * k))
    rotate_row("s3", 0, ("s0", "s1", "s2"))
    rotate_row("s4", 1, ("s0", "s1", "s2"))
    rotate_row("s5", 2, ("s0", "s1", "s2"))
    a("vadd(s5, s5, s25)")
    a("vdiv(s6, s31, s5)")
    a("vmul(s7, s3, s26)")
    a("vmul(s7, s7, s6)")
    a("vadd(s7, s27, s7)")
    a("vmul(s8, s4, s26)")
    a("vmul(s8, s8, s6)")
    a("vsub(s8, s28, s8)")
    a("vmul(s9, s5, s29)")
    store("s7", 0)
    store("s8", 2)
    store("s9", 4)
    for k in range(3):
        a("vldr(s%d, [r1, %d])" % (k, 4 * k))
    rotate_row("s3", 0, ("s0", "s1", "s2"))
    rotate_row("s4", 1, ("s0", "s1", "s2"))
    a("vmul(s3, s3, s30)")
    a("vmul(s4, s4, s30)")
    store("s3", 6, True)
    store("s4", 8, True)
    a("add(r0, 12)")
    a("add(r1, 12)")
    a("add(r2, 10)")
    a("sub(r3, r3, 1)")
    a("bgt_w(vertex)")

    a("ldr(r0, %s)" % at("X_FACES_ON"))
    a("cmp(r0, 0)")
    a("beq_w(done)")
    a("ldr(r0, %s)" % at("X_FACE_NORMALS"))
    a("ldr(r2, %s)" % at("X_FACES"))
    a("ldr(r3, %s)" % at("X_TRIS"))
    a("label(face)")
    for k in range(3):
        a("vldr(s%d, [r0, %d])" % (k, 4 * k))
    rotate_row("s3", 0, ("s0", "s1", "s2"))
    rotate_row("s4", 1, ("s0", "s1", "s2"))
    a("vmul(s3, s3, s30)")
    a("vmul(s4, s4, s30)")
    # packed: (x + offset) << 8 | (y + offset)
    a("vcvt_s32_f32(s3, s3)")
    a("vmov(r4, s3)")
    a("add(r4, %d)" % consts["NORMAL_OFFSET"])
    a("lsl(r4, r4, 8)")
    a("vcvt_s32_f32(s4, s4)")
    a("vmov(r5, s4)")
    a("add(r5, %d)" % consts["NORMAL_OFFSET"])
    a("orr(r4, r5)")
    a("strh(r4, [r2, 0])")
    a("add(r0, 12)")
    a("add(r2, 2)")
    a("sub(r3, r3, 1)")
    a("bgt_w(face)")

    a("label(done)")
    for i in range(16):
        a("vldr(s%d, %s)" % (16 + i, at("X_SAVE", i)))
    a("pop({r0})")
    if 2 * consts["VERT"] != 10:
        raise SystemExit("the stores assume 5 u16 per vertex")
    head = HEAD
    out = ROOT / "turbo_source" / "mesh_asm.py"
    out.write_text(HEADER + head + "".join("    %s\n" % l for l in lines))
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
