"""Writes the tables aprs_core.h includes: aprs_dec_taps.h (the /2
low-pass), aprs_pre_taps.h (the band-pass before the correlators) and
aprs_sin.h."""
import math
from pathlib import Path

here = Path(__file__).resolve().parent
DEC_TAPS, DEC_CUTOFF, IN_RATE = 24, 3800.0, 32000.0
PRE_TAPS, PRE_LO, PRE_HI, RATE = 47, 800.0, 2600.0, 16000.0


HEADER = ('// SPDX-FileCopyrightText: Copyright (c) 2026 Tim Cocks for Adafruit Industries\n'
          '//\n'
          '// SPDX-License-Identifier: MIT\n'
          '// Generated by gen_tables.py\n')


def write(name, values):
    lines = ['    ' + ', '.join('%.9ef' % v for v in values[i:i + 6]) + ','
             for i in range(0, len(values), 6)]
    (here / name).write_text(HEADER + '\n'.join(lines) + '\n')


fc = DEC_CUTOFF / IN_RATE
mid = (DEC_TAPS - 1) / 2
taps = []
for k in range(DEC_TAPS):
    x = k - mid
    sinc = 2 * fc * (math.sin(2 * math.pi * fc * x) / (2 * math.pi * fc * x) if x else 1.0)
    taps.append(sinc * (0.54 - 0.46 * math.cos(2 * math.pi * k / (DEC_TAPS - 1))))
total = sum(taps)
write('aprs_dec_taps.h', [t / total for t in taps])

# Band-pass: difference of two windowed sincs (Hamming), unity gain at 1700 Hz.
pre = []
mid = (PRE_TAPS - 1) / 2
for k in range(PRE_TAPS):
    x = k - mid
    def lp(cutoff):
        f = cutoff / RATE
        return 2 * f * (math.sin(2 * math.pi * f * x) / (2 * math.pi * f * x) if x else 1.0)
    window = 0.54 - 0.46 * math.cos(2 * math.pi * k / (PRE_TAPS - 1))
    pre.append((lp(PRE_HI) - lp(PRE_LO)) * window)
re = sum(h * math.cos(2 * math.pi * 1700 / RATE * k) for k, h in enumerate(pre))
im = sum(h * math.sin(2 * math.pi * 1700 / RATE * k) for k, h in enumerate(pre))
write('aprs_pre_taps.h', [h / math.hypot(re, im) for h in pre])

write('aprs_sin.h', [math.sin(2 * math.pi * k / 256) for k in range(256)])
