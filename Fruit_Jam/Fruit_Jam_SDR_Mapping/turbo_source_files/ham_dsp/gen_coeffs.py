"""Generate ham_coeffs.h: Kaiser-windowed low-pass FIR and biquad constants.

Run with numpy available: python3 gen_coeffs.py
"""

import math
from pathlib import Path
import numpy as np
# pylint: disable=redefined-outer-name
HERE = Path(__file__).resolve().parent


def kaiser_beta(atten):
    if atten > 50:
        return 0.1102 * (atten - 8.7)
    return 0.5842 * (atten - 21) ** 0.4 + 0.07886 * (atten - 21)


def lowpass(taps, cutoff, fs, atten=65, gain=1.0):
    """Linear-phase low-pass, DC gain `gain`, -6 dB at `cutoff` Hz."""
    n = np.arange(taps) - (taps - 1) / 2
    h = 2 * cutoff / fs * np.sinc(2 * cutoff / fs * n)
    h *= np.kaiser(taps, kaiser_beta(atten))
    return h / h.sum() * gain


def response_db(h, f, fs):
    w = 2 * np.pi * f / fs
    return 20 * np.log10(abs(np.sum(h * np.exp(-1j * w * np.arange(len(h))))) + 1e-12)


def butter2(kind, fc, fs):
    """RBJ cookbook 2nd-order Butterworth biquad, normalized a0 = 1."""
    w = 2 * math.pi * fc / fs
    alpha = math.sin(w) / (2 * math.sqrt(0.5))
    c = math.cos(w)
    if kind == "lp":
        b = ((1 - c) / 2, 1 - c, (1 - c) / 2)
    else:
        b = ((1 + c) / 2, -(1 + c), (1 + c) / 2)
    a0 = 1 + alpha
    return (b[0] / a0, b[1] / a0, b[2] / a0, -2 * c / a0, (1 - alpha) / a0)


# name: (taps, cutoff, fs, gain, [(freq, max_db or None for passband report)])
FIRS = {
    # 256 kHz -> 32 kHz. Keeps +-8 kHz; anything that would alias into
    # +-8 kHz (>= 24 kHz away) is attenuated by the stopband.
    "ham_f1": (64, 16000, 256000, 1.0),
    # NFM channel at 32 kHz complex: +-7.5 kHz passes, >= 11 kHz rejected.
    "ham_fnfm": (48, 9250, 32000, 1.0),
    # 32 kHz -> 8 kHz. Keeps +-3.2 kHz, rejects what aliases into it.
    "ham_f2": (64, 4000, 32000, 1.0),
    # Channel filters at 8 kHz complex, centred on the passband.
    "ham_fssb": (128, 1375, 8000, 1.0),  # 2.75 kHz wide (300..3050 Hz audio)
    "ham_fcw": (128, 300, 8000, 1.0),  # ~500 Hz wide
    "ham_fam": (128, 3300, 8000, 1.0),  # +-3.3 kHz
    # 8 kHz -> 32 kHz interpolator (gain 4 restores the level after zero
    # stuffing). Passes 3.2 kHz, rejects the 8 kHz images.
    "ham_fint": (64, 4000, 32000, 4.0),
}

lines = [
    "// SPDX-FileCopyrightText: Copyright (c) 2026 Tim Cocks for Adafruit Industries",
    "//",
    "// SPDX-License-Identifier: MIT",
    "// Generated by gen_coeffs.py. Do not edit.",
    "#ifndef HAM_COEFFS_H",
    "#define HAM_COEFFS_H",
]
report = {}
for name, (taps, cutoff, fs, gain) in FIRS.items():
    h = lowpass(taps, cutoff, fs, gain=gain)
    lines.append("#define %s_TAPS %d" % (name.upper(), taps))
    lines.append("static const float %s[%d] = {" % (name, taps))
    lines += ["    %.9ef," % v for v in h]
    lines.append("};")
    pts = sorted({0, cutoff * 0.8, cutoff, cutoff * 1.25, cutoff * 1.6, fs / 2})
    report[name] = {int(f): round(float(response_db(h / gain, f, fs)), 1) for f in pts}

# NFM audio at 32 kHz: CTCSS/hum high-pass at 300 Hz, voice low-pass at 3.4 kHz.
for name, kind, fc in (("ham_nfm_hp", "hp", 300), ("ham_nfm_lp", "lp", 3400)):
    b0, b1, b2, a1, a2 = butter2(kind, fc, 32000)
    lines.append(
        "static const float %s[5] = {%.9ef, %.9ef, %.9ef, %.9ef, %.9ef};"
        % (name, b0, b1, b2, a1, a2)
    )
lines.append("#endif")
(HERE / "ham_coeffs.h").write_text("\n".join(lines) + "\n")
if __name__ == "__main__":
    for k, v in report.items():
        print(k, v)
