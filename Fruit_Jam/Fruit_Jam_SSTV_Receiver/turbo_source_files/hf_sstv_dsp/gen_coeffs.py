"""Generate hf_coeffs.h: the FIR filters of the HF SSTV detector and decoder.

Run with numpy available: python3 gen_coeffs.py
"""

from pathlib import Path
import numpy as np
# pylint: disable=redefined-outer-name
HERE = Path(__file__).resolve().parent


def kaiser_beta(atten):
    if atten > 50:
        return 0.1102 * (atten - 8.7)
    return 0.5842 * (atten - 21) ** 0.4 + 0.07886 * (atten - 21)


def lowpass(taps, cutoff, fs, atten=60):
    """Linear-phase low-pass, DC gain 1, -6 dB at `cutoff` Hz."""
    n = np.arange(taps) - (taps - 1) / 2
    h = 2 * cutoff / fs * np.sinc(2 * cutoff / fs * n)
    h *= np.kaiser(taps, kaiser_beta(atten))
    return h / h.sum()


def response_db(h, f, fs):
    w = 2 * np.pi * f / fs
    return 20 * np.log10(abs(np.sum(h * np.exp(-1j * w * np.arange(len(h))))) + 1e-12)


# name: (taps, cutoff, fs)
FIRS = {
    # 32 kHz -> 8 kHz for the ring and the WAV files. The USB demodulator
    # passes 300..3050 Hz; flat to about 2.6 kHz (SSTV tones reach 2300 Hz,
    # plus the sender's tuning error), and what aliases back below 3 kHz
    # (>= 5 kHz) is in the stopband.
    "hf_decim": (48, 3400, 32000),
    # Tones mixed down by 1700 Hz (1100..2300 Hz -> -600..+600 Hz, up to
    # +-250 Hz more for tuning error): keep +-850 Hz and reject the mixing
    # image (-2550 Hz and beyond).
    "hf_lp": (32, 1150, 8000),
}


def taps(name):
    t, cutoff, fs = FIRS[name]
    return lowpass(t, cutoff, fs)


if __name__ == "__main__":
    lines = [
        "// SPDX-FileCopyrightText: Copyright (c) 2026 Tim Cocks for Adafruit Industries",
        "//",
        "// SPDX-License-Identifier: MIT",
        "// Generated by gen_coeffs.py. Do not edit.",
        "#ifndef HF_COEFFS_H",
        "#define HF_COEFFS_H",
    ]
    for name, (t, cutoff, fs) in FIRS.items():
        h = taps(name)
        lines.append("#define %s_TAPS %d" % (name.upper(), t))
        lines.append("static const float %s[%d] = {" % (name, t))
        lines += ["    %.9ef," % v for v in h]
        lines.append("};")
        pts = sorted(
            {0, 850, cutoff * 0.75, cutoff, cutoff * 1.5, cutoff * 2.2, fs / 2}
        )
        print(name, {int(f): round(float(response_db(h, f, fs)), 1) for f in pts})
    # exp(-j 2 pi k / 80) (the 1700 Hz mixer at 8 kHz repeats every 80
    # samples, 17 turns) and exp(-j 2 pi k / 160) (DFT phasors for tones on
    # the 50 Hz grid around 1700 Hz repeat every 160 samples).
    for name, n in (("hf_mix80", 80), ("hf_rot160", 160)):
        k = 17 * np.arange(n) if n == 80 else np.arange(n)
        lines.append("static const float %s[%d][2] = {" % (name, n))
        lines += [
            "    {%.9ef, %.9ef},"
            % (np.cos(2 * np.pi * v / n), -np.sin(2 * np.pi * v / n))
            for v in k
        ]
        lines.append("};")
    lines.append("#endif")
    (HERE / "hf_coeffs.h").write_text("\n".join(lines) + "\n")
